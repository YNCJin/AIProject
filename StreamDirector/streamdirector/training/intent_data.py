_FILLERS = {"e": _REQ_END, "e2": ["줘", "주세요", "라", "줄래", "봐", "주라"]}


def _fill(seed: str, rng: random.Random) -> str:
    out = seed
    for key, choices in _FILLERS.items():
        out = out.replace("{" + key + "}", rng.choice(choices))
    return out


def _augment(text: str, rng: random.Random) -> str:
    t = rng.choice(_PRE) + text + rng.choice(_POST)
    r = rng.random()
    if r < 0.15:
        t = t.replace(" ", "")  # 띄어쓰기 생략
    elif r < 0.25 and len(t) > 3:
        i = rng.randrange(len(t))
        t = t[:i] + t[i] + t[i:]  # 오타성 글자 반복
    return t.strip()


def build_dataset(per_class: int = 300, seed: int = 42, exclude: set[str] | None = None) -> list[dict]:
    rng = random.Random(seed)
    exclude = {e.strip() for e in (exclude or set())}
    rows: list[dict] = []
    pools = {**COMMAND_SEEDS, "GAME_TALK": GAME_TALK, "OFF_TOPIC": OFF_TOPIC}
    for label in LABELS:
        seen: set[str] = set()
        seeds = pools[label]
        attempts = 0
        while len(seen) < per_class and attempts < per_class * 30:
            attempts += 1
            text = _augment(_fill(rng.choice(seeds), rng), rng)
            if text in exclude or text in seen:
                continue
            seen.add(text)
        rows += [{"text": t, "label": label} for t in seen]
    rng.shuffle(rows)
    return rows
